/**
 * Pure builders for the WowUp.Addon companion-data payload.
 *
 * Schema verified against the actual templates WowUp's desktop client
 * compiles (GPL-3.0, WowUp/WowUp@4fdae600, confirmed byte-identical to
 * upstream master as of 2026-10-11):
 *   wowup-electron/assets/WowUpAddon/data.lua.hbs
 *   wowup-electron/assets/WowUpAddon/wowup_data_addon.toc.hbs
 * and the documented contract (WowUp/WowUp.Addon@6c9304b):
 *   AddonManagers.md
 * See docs/wowup-provenance.md.
 *
 * Deliberately NOT a Handlebars port: this project has no templating
 * dependency and the schema is tiny, so the Lua/TOC text is built
 * directly from these functions instead of adding one.
 */

import { MANAGER_ACCENT_RGB, MANAGER_NAME, WOWUP_ADDON_FOLDER_NAME } from "./constants";

export interface CompanionUpdateEntry {
  name: string;
  currentVersion: string;
  newVersion: string;
}

/**
 * Lua string literal, safe for arbitrary addon names/versions (Stage
 * 4.2) — escapes backslash, double-quote and control characters only.
 * WoW's Lua 5.1 treats strings as raw byte arrays, so multi-byte UTF-8
 * (accents, CJK, emoji) round-trips untouched without special handling;
 * this never needs to concatenate user-controlled text directly into
 * the surrounding Lua source.
 */
export function luaString(value: string): string {
  return `"${value
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/\r/g, "\\r")
    .replace(/\t/g, "\\t")}"`;
}

/** `WOWUP_DATA` — see AddonManagers.md. Omits `icon`/slash-command: no minimap asset is bundled and this manager has no in-game command to open. */
export function buildDataLua(updates: CompanionUpdateEntry[], generatedAt: Date): string {
  const [r, g, b] = MANAGER_ACCENT_RGB;
  const rows = updates
    .map((u) => `  [${luaString(u.name)}] = {${luaString(u.currentVersion)}, ${luaString(u.newVersion)}},`)
    .join("\n");
  return [
    `-- this file is autogenerated by ${MANAGER_NAME} at ${generatedAt.toISOString()}`,
    `WOWUP_DATA = {}`,
    `WOWUP_DATA.addonManagerName = ${luaString(MANAGER_NAME)}`,
    `WOWUP_DATA.addonManagerColorRGB = {${r.toFixed(4)},${g.toFixed(4)},${b.toFixed(4)}}`,
    `WOWUP_DATA.updateAddonsList = {`,
    rows,
    `}`,
    "",
  ].join("\n");
}

export interface CompanionTocOptions {
  /** Numeric WoW Interface version, e.g. "110002" (see utils/gameversion.ts's toInterfaceVersion). */
  interfaceVersion: string;
  /** This bridge's own data-schema version (COMPANION_DATA_VERSION), not the companion addon's version. */
  dataVersion: string;
}

/** `wowup_data_addon.toc` — `RequiredDeps` ties loading to the real companion addon being present/enabled. */
export function buildCompanionToc({ interfaceVersion, dataVersion }: CompanionTocOptions): string {
  return [
    `## Interface: ${interfaceVersion}`,
    `## Title: Addon Update Notifications (${MANAGER_NAME} Data)`,
    `## Notes: Update data generated by ${MANAGER_NAME} for the WowUp companion addon. Do not edit by hand.`,
    `## Author: ${MANAGER_NAME}`,
    `## Version: ${dataVersion}`,
    `## DefaultState: enabled`,
    `## RequiredDeps: ${WOWUP_ADDON_FOLDER_NAME}`,
    `## X-AddonProvider: wowdeck`,
    "",
    "data.lua",
    "",
  ].join("\n");
}
